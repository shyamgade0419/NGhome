const { withAndroidManifest } = require('expo/config-plugins');

/**
 * Play Console warns that "required hardware feature declarations are restricting your app's availability".
 * We never declare these features: Google infers them (ACCESS_WIFI_STATE implies android.hardware.wifi, and a
 * portrait-locked screen implies android.hardware.screen.portrait) and treats an inferred feature as required,
 * which hides the app from devices without it (Android TV, Chromebooks, some tablets).
 *
 * Declaring each as required="false" overrides the inference. The app works without either: it only needs a
 * network connection, which mobile data gives it too, and it still opens in portrait where that exists.
 *
 * A config plugin rather than a hand edit because android/ is generated by `expo prebuild` and gitignored.
 */
const OPTIONAL_FEATURES = ['android.hardware.wifi', 'android.hardware.screen.portrait'];

module.exports = function withOptionalHardware(config) {
  return withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults.manifest;
    const features = (manifest['uses-feature'] = manifest['uses-feature'] ?? []);
    for (const name of OPTIONAL_FEATURES) {
      const existing = features.find((f) => f.$['android:name'] === name);
      if (existing) existing.$['android:required'] = 'false';
      else features.push({ $: { 'android:name': name, 'android:required': 'false' } });
    }
    return cfg;
  });
};
